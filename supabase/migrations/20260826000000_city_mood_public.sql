-- Gives the API/embeddable-badge surface a server-side place to read the
-- same "current reading" every page on the site already shows for a
-- city -- the real, curated mood/band value that has lived only in the
-- static cities-data.js bundle until now. Nothing new is invented here:
-- this table is seeded with the exact same numbers cities-data.js
-- already carries, so a badge embedded on someone else's site never
-- disagrees with what that city's own Glotemp page says.
--
-- Deliberately separate from `observations` (real crowd check-ins, the
-- thing the paid /v1/cities/{slug} endpoint reports) and from `readings`
-- (the 12-vertical collector facts). Those two are their own honest,
-- separately-sourced products; this table is the one number every city
-- page already treats as canonical, made reachable from server code.
create table if not exists city_mood (
  city_slug text primary key,
  mood numeric not null check (mood >= 0 and mood <= 10),
  band text not null check (band in ('charged', 'warm', 'equilibrium', 'restrained', 'low')),
  updated_at timestamptz not null default now()
);

comment on table city_mood is
  'Mirror of the per-city mood/band value cities-data.js already treats as real and shows everywhere (band coloring, hover previews, the City reading section). Exists so server-side code (the public API, the embeddable badge) can read the same number a visitor already sees on that city''s own page, rather than a second, disagreeing figure.';

-- Public, read-only, no auth needed: this is the same data every static
-- page already ships to every visitor.
alter table city_mood enable row level security;
drop policy if exists city_mood_public_read on city_mood;
create policy city_mood_public_read on city_mood for select using (true);

