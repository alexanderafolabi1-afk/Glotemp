-- WHY job=nowplaying WAS RETURNING A BARE 502
-- Same missing table. jobNowPlaying's first read from city_stations threw
-- before there was anything to iterate, and the top-level catch turned
-- that into a 502. The error text it already carried named city_stations
-- specifically; music-sync/index.ts now also collects and returns the
-- per-city/per-station error detail instead of only console.error-ing it.
--
