-- 1. city_points held 151 of the site's 300 cities (seeded once, in
--    20260816180000, from an older, shorter city list, and never
--    refreshed). job=stations reads its city set from city_points, so no
--    code change removing a "25-city limit" can cover more than this
--    table actually holds. Backfilled here from the same lat/lon already
--    shipped in cities-data.js. on conflict do nothing: existing rows
--    (and their radius_km, if ever hand-tuned) are left alone.
-- 2. Reschedules glotemp-music-nowplaying from every 10 minutes to every
--    15 (the requested cadence), offset to :05/:20/:35/:50 rather than
--    the top of the hour so it never lands on the same minute as
--    transitland-transport (:45) or waqi-health (:15) -- a deliberate
--    stagger, not just a period change. Stations, artists and events keep
--    the cadence and offsets 20260817090000 already gave them (weekly,
