-- WHY job=stations WAS RETURNING 200 WITH {"cities": 25, "stations": 0}
-- Not a Radio Browser problem and not a filter problem: 20260817090000
-- (the migration that creates city_stations, now_playing and everything
-- else the music layer needs) was written and merged but never applied to
-- this database. Every insert into city_stations was failing with a real
-- "relation does not exist" error -- caught per-city, logged, and
